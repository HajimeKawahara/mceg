def _append_inventory(original: str, additions: dict) -> str:
    """Append to the three root lists while retaining existing YAML and comments."""
    tree = yaml.compose(original)
    patches = []
    for field, items in additions.items():
        if not items:
            continue
        key, node = next(((key, node) for key, node in tree.value if key.value == field), (None, None))
        if not isinstance(node, yaml.SequenceNode) or node.start_mark.index < key.end_mark.index:
            raise ValueError(f"Inventory {field} must be a direct YAML list, not an alias or merged key")
        if node.flow_style:
            # A JSON value is also valid inside a YAML flow sequence.
            tokens = list(yaml.scan(original[node.start_mark.index:node.end_mark.index]))
            trailing_comma = isinstance(tokens[-3], yaml.tokens.FlowEntryToken)
            prefix = ", " if node.value and not trailing_comma else ""
            addition = prefix + ", ".join(json.dumps(item, allow_nan=False) for item in items)
            offset = node.end_mark.index - 1
        else:
            offset = node.end_mark.index
            if offset != len(original):
                offset -= node.end_mark.column
            addition = textwrap.indent(yaml.safe_dump(items, sort_keys=False, allow_unicode=True),
                                       " " * node.start_mark.column)
            if offset and original[offset - 1] != "\n":
                addition = "\n" + addition
        patches.append((offset, addition))
    for offset, addition in sorted(patches, reverse=True):
        original = original[:offset] + addition + original[offset:]
    return original


def _write_new(path, text):
    created = False
    try:
        with path.open("x", encoding="utf-8") as stream:
            created = True
            stream.write(text)
    except OSError:
        if created:
            path.unlink()
        raise


def _write_files(contract_path, contract_text, inventory_path, inventory_text, original):
    contract_path.parent.mkdir(parents=True, exist_ok=True)
    _write_new(contract_path, contract_text)
    temporary = None
    try:
        if original is None:
            _write_new(inventory_path, inventory_text)
        else:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=inventory_path.parent,
                                             prefix=".mceg-init-", delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(inventory_text)
            temporary.chmod(inventory_path.stat().st_mode & 0o777)
            if inventory_path.read_bytes() != original:
                raise ValueError("Inventory changed during initialization; retry with the current file")
            os.replace(temporary, inventory_path)
    except (OSError, ValueError):
        contract_path.unlink()
        raise
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def initialize(root: str | Path, model_id: str, source: str, symbol: str, *,
               settings: dict | None = None, repository: str | None = None,
               revision: str | None = None) -> Path:
    """Create one draft and append its pending mapping; preserve existing records."""
    root = Path(root).resolve()
    if not root.is_dir():
        raise ValueError(f"Provider root is not a directory: {root}")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", model_id):
        raise ValueError("Model ID must start with a letter/digit and use letters, digits, '.', '_' or '-'")
    binding = Binding(path=source, symbol=symbol, settings=settings or {})
    path = _local(root, binding.path)
    if path.suffix != ".py" or binding.symbol not in _symbols(path.read_bytes(), binding.path):
        raise ValueError(f"No local Python definition {symbol!r} in {source!r}")
    contract_relative = f"mceg/contracts/{model_id}.yaml"
    contract_path = _local(root, contract_relative)
    if contract_path.exists():
        raise ValueError(f"Contract already exists: {contract_relative}")
    inventory_path = _local(root, "mceg/models.yaml")
    original = inventory_path.read_bytes() if inventory_path.exists() else None
    data = read_document(inventory_path) if original is not None else {
        "inventory_version": "0.1",
        "scope": "Initial inventory of explicitly selected files; review and expand source_roots for package coverage.",
        "source_roots": [binding.path], "contract_roots": ["mceg/contracts"], "files": {}, "models": [],
    }
    inventory = Inventory.model_validate(data)
    if model_id in {model.id for model in inventory.models}:
        raise ValueError(f"Model ID already inventoried: {model_id}; edit its existing entry")
    # Also protect a declared link whose file has gone missing.
    if any(link.path == contract_relative or link.model_id == model_id
           for model in inventory.models for link in model.contracts):
        raise ValueError(f"Contract identity already inventoried: {model_id}; review the existing link")
    model = {"id": model_id, "description": "TODO: Review this model boundary and its selected choices.",
             "review_pending": True, "bindings": [binding.model_dump(exclude_none=True)],
             "contracts": [{"path": contract_relative, "model_id": model_id}]}
    additions = {"models": [model],
                 "source_roots": [] if _in_scope(binding.path, inventory.source_roots) else [binding.path],
                 "contract_roots": [] if _in_scope(contract_relative, inventory.contract_roots) else ["mceg/contracts"]}
    for field, items in additions.items():
        data[field].extend(items)
    expected = Inventory.model_validate(data)
    inventory_text = (_append_inventory(original.decode("utf-8"), additions) if original is not None else
                      yaml.safe_dump(data, sort_keys=False, allow_unicode=True))
    # Check that comment-preserving insertion has exactly the intended semantics.
    if Inventory.model_validate(yaml.safe_load(inventory_text)) != expected:
        raise ValueError("Cannot safely append to this inventory layout")
    if revision is None:
        head = _git(root, "rev-parse", "--verify", "HEAD")
        revision = "unreviewed working tree" + (f" based on {head}" if head else "")
    if repository is None:
        repository = _git(root, "config", "--get", "remote.origin.url") or "unknown"
    contract = _contract(model_id, binding, repository, revision)
    _write_files(contract_path, yaml.safe_dump(contract, sort_keys=False, allow_unicode=True),
                 inventory_path, inventory_text, original)
    return contract_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="mceg init", description="Create a v0.2 draft and register a new model for review.",
        epilog="No provider imports, scientific review or test execution. Exit codes: 0 created, 2 invalid input/write error.")
    parser.add_argument("model_id", help="New model ID; also the contract filename under mceg/contracts/")
    parser.add_argument("--source", required=True, help="Python implementation path relative to the provider root")
    parser.add_argument("--symbol", required=True, help="Local definition, e.g. concentration or Host.response")
    parser.add_argument("--setting", action="append", default=[], metavar="KEY=VALUE",
                        help="Model choice; repeatable, JSON scalar or plain text")
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="Provider root (default: cwd)")
    parser.add_argument("--repository", help="Repository identity (default: Git origin, otherwise unknown)")
    parser.add_argument("--revision", help="Implementation identity (default: unreviewed working tree, with Git HEAD if available)")
    args = parser.parse_args(argv)
    try:
        path = initialize(args.root, args.model_id, args.source, args.symbol, settings=_settings(args.setting),
                          repository=args.repository, revision=args.revision)
    except (OSError, ValueError, SyntaxError, yaml.YAMLError) as exc:
        parser.error(str(exc))
    print(f"Created {path}")
    print(f"Registered {args.model_id} in {args.root.resolve() / 'mceg/models.yaml'}; review pending.")
    print("Review the TODO fields, model choices and sources before recording file reviews or assessments.")
    print("Coverage will report unreviewed_model until its inventory review_pending flag is cleared after review.")
    print("Next steps:")
    for command in (["mceg", "check", str(path)], ["mceg", "explain", str(path), "--evidence", "implementation"],
                    ["mceg", "coverage", str(args.root.resolve())]):
        print("  " + shlex.join(command))
    return 0
