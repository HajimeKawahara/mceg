"""Export authored equation definitions as TeX without running a provider or TeX."""

import argparse
from pathlib import Path
import sys

import yaml

from .schema_v03 import ContractV03, equation_digest
from .validator import load_contract


def tex_text(value):
    """Escape prose while leaving the separate authored math fields untouched."""
    replacements = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in " ".join(str(value).split()))


def equation_label(model_id, equation_id, revision):
    """Return an unambiguous TeX label; underscores introduce UTF-8 escapes."""
    def component(value):
        return "".join(char if char.isascii() and (char.isalnum() or char in ".-")
                       else "_" + char.encode("utf-8").hex() + "_" for char in value)

    return "eq:" + ":".join(component(part) for part in (model_id, equation_id, revision))


def render_equations(contract):
    """Return a deterministic fragment for an amsmath document, not a proof."""
    if not isinstance(contract, ContractV03):
        raise ValueError("Equation export requires a schema 0.3 contract")
    lines = [
        "% Generated by mceg equations; edit the contract, then regenerate.",
        "% Requires amsmath. Authored math is retained; TeX is not executed here.",
        "% Definitions and hashes do not establish scientific validity.",
        "",
    ]
    for equation in contract.equations:
        label = equation_label(contract.model.id, equation.id, equation.revision)
        lines.extend([
            "% equation-sha256: " + equation_digest(equation),
            r"\paragraph{Equation " + tex_text(equation.id) + " (revision "
            + tex_text(equation.revision) + ")}",
            tex_text(equation.description),
            r"\begin{equation}",
            r"\begin{aligned}",
            equation.latex,
            r"\end{aligned}",
            r"\label{" + label + "}",
            r"\end{equation}",
            r"\noindent\textbf{Scope:} " + tex_text(equation.scope),
            "",
        ])
        if equation.symbols:
            lines.append(r"\begin{description}")
            for key, symbol in equation.symbols.items():
                lines.append(r"\item[$" + symbol.latex + "$] " + tex_text(symbol.description)
                             + " (" + tex_text(symbol.unit) + "; ID: " + tex_text(key) + ").")
            lines.extend([r"\end{description}", ""])
        if equation.assumptions:
            lines.extend([r"\noindent\textbf{Assumptions:}", r"\begin{itemize}"])
            lines.extend(r"\item " + tex_text(item) for item in equation.assumptions)
            lines.extend([r"\end{itemize}", ""])
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="mceg equations", description="Export recorded definitions; do not execute or prove them.",
    )
    parser.add_argument("contract", type=Path)
    parser.add_argument("--output", type=Path, required=True, help="Generated TeX fragment")
    parser.add_argument("--check", action="store_true", help="Fail if output is missing or stale; write nothing")
    args = parser.parse_args(argv)
    try:
        if args.contract.resolve() == args.output.resolve() or (
            args.output.exists() and args.contract.samefile(args.output)
        ):
            raise ValueError("Output must not overwrite the input contract")
        rendered = render_equations(load_contract(args.contract)).encode("utf-8")
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != rendered:
                print(f"STALE {args.output}: regenerate from the contract", file=sys.stderr)
                return 1
            print(f"MATCH {args.output}: generated bytes only; no scientific assessment")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(rendered)
            print(f"WROTE {args.output}")
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
