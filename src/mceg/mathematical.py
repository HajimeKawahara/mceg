"""Export declared quantity--relation connections without executing a model."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import yaml

from .equations import equation_label, equation_latex, tex_text
from .schema_v05 import ContractV05, mathematical_model_digest
from .validator import load_contract


def _prose(value):
    """Escape text, including comparison signs outside math mode."""
    return tex_text(value).replace("<", r"\textless{}").replace(">", r"\textgreater{}")


def select_model(contract, model_id, revision=None):
    """Select one exact definition; never guess between recorded revisions."""
    if not isinstance(contract, ContractV05):
        raise ValueError("Mathematical model export requires a schema 0.5 contract")
    candidates = [model for model in contract.mathematical_models
                  if model.id == model_id and (revision is None or model.revision == revision)]
    if not candidates:
        raise ValueError(f"Unknown mathematical model: {model_id!r}, revision {revision!r}")
    if len(candidates) != 1:
        raise ValueError(f"Ambiguous mathematical model {model_id!r}; specify --revision")
    return candidates[0]


def model_graph(contract, model_id, revision=None):
    """Return a bipartite incidence graph, not a directed computation graph."""
    model = select_model(contract, model_id, revision)
    quantities = {(item.id, item.revision): item for item in contract.quantities}
    equations = {(item.id, item.revision): item for item in contract.equations}
    nodes, edges = [], []
    for alias, item in sorted(model.quantities.items()):
        quantity = quantities[item.quantity.id, item.quantity.revision]
        nodes.append({"id": "quantity:" + alias, "type": "quantity", "alias": alias,
                      "role": item.role, "definition": quantity.model_dump(mode="json")})
    for relation in sorted(model.relations, key=lambda item: item.id):
        equation = equations[relation.equation.id, relation.equation.revision]
        nodes.append({"id": "relation:" + relation.id, "type": "relation",
                      "instance": relation.id, "kind": relation.kind, "role": relation.role,
                      "equation": equation.model_dump(mode="json")})
        if getattr(equation, "sympy", None) is not None:
            nodes[-1]["display_latex"] = equation_latex(equation)
        for symbol, alias in sorted(relation.quantities.items()):
            edges.append({"quantity": "quantity:" + alias, "relation": "relation:" + relation.id,
                          "symbol": symbol})
    return {
        "format": "mceg_mathematical_graph_v1", "directed": False,
        "contract": contract.model.id,
        "model": {key: getattr(model, key) for key in ("id", "revision", "description", "scope")},
        "sha256": mathematical_model_digest(contract, model.id, model.revision),
        "interpretation": "Declared symbol incidence only; no execution order or scientific support is inferred.",
        "nodes": nodes, "edges": edges,
    }


def _mermaid_text(value):
    replacements = {"&": "#38;", '"': "#34;", "<": "#60;", ">": "#62;", "#": "#35;",
                    "\\": "#92;", "|": "#124;"}
    return "".join(replacements.get(char, char) for char in " ".join(str(value).split()))


def render_mermaid(graph):
    """Render a deterministic, undirected diagram with escaped text labels."""
    lines = ["flowchart LR", "    %% Declared incidence, not execution order or scientific support."]
    identifiers = {node["id"]: f"n{i}" for i, node in enumerate(graph["nodes"])}
    for node in graph["nodes"]:
        identifier = identifiers[node["id"]]
        if node["type"] == "quantity":
            label = _mermaid_text(f"{node['alias']} ({node['role']})")
            lines.append(f'    {identifier}(("{label}"))')
        else:
            label = _mermaid_text(f"{node['instance']}: {node['role']}")
            lines.append(f'    {identifier}["{label}"]')
    for edge in graph["edges"]:
        lines.append(f'    {identifiers[edge["relation"]]} ---|"{_mermaid_text(edge["symbol"])}"| '
                     f'{identifiers[edge["quantity"]]}')
    return "\n".join(lines) + "\n"


def render_model_tex(contract, model_id, revision=None):
    """Render adopted equations, quantity meanings and their explicit connections."""
    model = select_model(contract, model_id, revision)
    graph = model_graph(contract, model.id, model.revision)
    quantities = {(item.id, item.revision): item for item in contract.quantities}
    equations = {(item.id, item.revision): item for item in contract.equations}
    lines = [
        "% Generated by mceg model; edit the contract, then regenerate.",
        "% Requires amsmath. Authored math is retained; TeX is not executed here.",
        "% mathematical-model-sha256: " + graph["sha256"],
        r"\subsection*{" + _prose(model.id) + " (revision " + _prose(model.revision) + ")}",
        _prose(model.description), "",
        r"\noindent\textbf{Scope:} " + _prose(model.scope), "",
        "These are declared mathematical relationships. Their presence does not establish",
        "existence or uniqueness of a solution, code correspondence, or physical adequacy.", "",
        r"\subsubsection*{Quantities}",
        r"\begin{description}",
    ]
    for alias, item in sorted(model.quantities.items()):
        quantity = quantities[item.quantity.id, item.quantity.revision]
        coordinates = ", ".join(f"{ref.id} ({ref.revision})" for ref in quantity.coordinates) or "none"
        lines.extend([
            r"\item[" + _prose(alias) + "] $" + quantity.latex + "$: " + _prose(quantity.description),
            r"\newline Role: " + _prose(item.role) + "; unit: " + _prose(quantity.unit) + ".",
            r"\newline Domain: " + _prose(quantity.domain),
            r"\newline Definition: " + _prose(quantity.id) + " (revision "
            + _prose(quantity.revision) + "); coordinates: " + _prose(coordinates) + ".",
        ])
    lines.extend([r"\end{description}", "", r"\subsubsection*{Adopted relations}", ""])
    for relation in model.relations:
        equation = equations[relation.equation.id, relation.equation.revision]
        label = equation_label(contract.model.id + ":" + model.id, relation.id, model.revision)
        lines.extend([
            r"\paragraph{" + _prose(relation.id) + "}",
            _prose(relation.role) + " (" + _prose(relation.kind) + "). " + _prose(equation.description),
            r"\begin{equation}", r"\begin{aligned}", equation_latex(equation),
            r"\end{aligned}", r"\label{" + label + "}", r"\end{equation}",
            r"\noindent\textbf{Definition:} " + _prose(equation.id) + " (revision "
            + _prose(equation.revision) + ").",
            r"\textbf{Scope:} " + _prose(equation.scope), "",
            r"\begin{description}",
        ])
        for symbol, alias in sorted(relation.quantities.items()):
            item = equation.symbols[symbol]
            lines.append(r"\item[$" + item.latex + "$] " + _prose(symbol) + r" $\mapsto$ "
                         + _prose(alias) + ". " + _prose(item.description))
        lines.extend([r"\end{description}", ""])
        if equation.assumptions:
            lines.extend([r"\noindent\textbf{Assumptions:}", r"\begin{itemize}"])
            lines.extend(r"\item " + _prose(item) for item in equation.assumptions)
            lines.extend([r"\end{itemize}", ""])
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="mceg model", description="Inspect a declared mathematical model without running it.",
    )
    parser.add_argument("contract", type=Path)
    parser.add_argument("--model", required=True, help="MathematicalModel ID")
    parser.add_argument("--revision", help="Required when the ID has several recorded revisions")
    parser.add_argument("--format", choices=("json", "mermaid", "tex"), default="json")
    parser.add_argument("--output", type=Path, help="Write an artifact instead of standard output")
    parser.add_argument("--check", action="store_true", help="Require matching output bytes; write nothing")
    args = parser.parse_args(argv)
    if args.check and args.output is None:
        parser.error("--check requires --output")
    try:
        if args.output is not None and (args.contract.resolve() == args.output.resolve() or (
            args.output.exists() and args.contract.samefile(args.output)
        )):
            raise ValueError("Output must not overwrite the input contract")
        contract = load_contract(args.contract)
        if args.format == "tex":
            rendered = render_model_tex(contract, args.model, args.revision)
        else:
            graph = model_graph(contract, args.model, args.revision)
            rendered = (render_mermaid(graph) if args.format == "mermaid"
                        else json.dumps(graph, indent=2, ensure_ascii=True) + "\n")
        if args.output is None:
            sys.stdout.write(rendered)
        elif args.check:
            if not args.output.is_file() or args.output.read_bytes() != rendered.encode("utf-8"):
                print(f"STALE {args.output}: regenerate from the contract", file=sys.stderr)
                return 1
            print(f"MATCH {args.output}: generated bytes only; no scientific assessment")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(rendered.encode("utf-8"))
            print(f"WROTE {args.output}")
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
