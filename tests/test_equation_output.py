ROOT = Path(__file__).resolve().parents[1]


def write_contract(tmp_path, data=None):
    path = tmp_path / "contract.json"
    path.write_text(json.dumps(example_data() if data is None else data), encoding="utf-8")
    return path


def test_export_and_check_are_deterministic_and_preserve_inputs(tmp_path, capsys):
    source = write_contract(tmp_path)
    before = source.read_bytes()
    output = tmp_path / "generated/equations.tex"
    arguments = [str(source), "--output", str(output)]
    assert main([*arguments, "--check"]) == 1
    assert not output.parent.exists()
    assert main(arguments) == 0
    content = output.read_bytes()
    assert main([*arguments, "--check"]) == 0
    assert main(arguments) == 0
    assert output.read_bytes() == content
    output.write_bytes(content + b"% Hand edit\n")
    assert main([*arguments, "--check"]) == 1
    assert output.read_bytes() == content + b"% Hand edit\n"
    assert source.read_bytes() == before
    assert "generated bytes only; no scientific assessment" in capsys.readouterr().out


@pytest.mark.parametrize("alias", ["same", "symlink", "hardlink"])
def test_export_never_overwrites_contract_aliases(tmp_path, alias):
    source = write_contract(tmp_path)
    output = source if alias == "same" else tmp_path / "output.tex"
    if alias == "symlink":
        output.symlink_to(source)
    elif alias == "hardlink":
        output.hardlink_to(source)
    before = source.read_bytes()
    assert main([str(source), "--output", str(output)]) == 1
    assert source.read_bytes() == before


