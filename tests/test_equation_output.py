def test_render_retains_math_but_escapes_prose_and_tracks_definitions():
    data = example_data()
    equation = data["equations"][0]
    equation["description"] = r"A 50% rate_1 & {bound} # $test$ \input{file} ~ ^"
    contract = ContractV03.model_validate(data)
    text = render_equations(contract)
    assert contract.equations[0].latex in text
    assert equation_digest(contract.equations[0]) in text
    assert tex_text(equation["description"]) in text
    assert r"\input{file}" not in text
    assert r"\label{" + equation_label(contract.model.id, equation["id"], equation["revision"]) + "}" in text
    changed = copy.deepcopy(data)
    symbol = next(iter(changed["equations"][0]["symbols"].values()))
    symbol["unit"] = "new unit"
    assert render_equations(ContractV03.model_validate(changed)) != text


def test_labels_keep_revision_identity_and_escape_separators():
    assert equation_label("escape.hydrogen", "continuity", "1") == "eq:escape.hydrogen:continuity:1"
    labels = [equation_label("model", key, revision) for key, revision in
              [("a:b", "1"), ("a", "b:1"), ("a_b", "1"), ("a_5f_b", "1")]]
    assert len(set(labels)) == len(labels)
    weird = equation_label("model %\\日本語", "x", "1")
    assert weird.isascii() and not any(char in weird for char in "%\\ {}")


def test_graph_exposes_equations_bindings_and_review_pins_without_support_edges(tmp_path):
    data = example_data()
    source = write_contract(tmp_path, data)
    before = source.read_bytes()
    graph = build_graph(paths=[source], root=tmp_path)
    nodes = {node["id"]: node for node in graph["nodes"]}
    equations = [node for node in nodes.values() if node["type"] == "equation"]
    bindings = [node for node in nodes.values() if node["type"] == "binding"]
    assert len(equations) == len(data["equations"])
    assert len(bindings) == len(data["bindings"])
    for node in equations:
        original = next(e for e in data["equations"] if e["id"] == node["ref"]["id"])
        assert node["ref"]["revision"] == original["revision"]
        assert node["record"]["latex"] == original["latex"]
    by_type = {}
    for edge in graph["edges"]:
        by_type.setdefault(edge["type"], []).append(edge)
    assert by_type["refers_to_equation"] and by_type["binds_equation"]
    assert by_type["pins_equation"] and by_type["pins_binding"]
    for edge in by_type["pins_equation"]:
        assert nodes[edge["source"]]["type"] == "assessment"
        assert nodes[edge["target"]]["type"] == "equation"
        assert len(edge["data"]["sha256"]) == 64
    assert any(nodes[edge["source"]]["type"] == "binding" for edge in by_type["has_subject"])
    assert "supports" not in by_type and "implements" not in by_type
    assert source.read_bytes() == before


def test_graph_distinguishes_equation_revisions(tmp_path):
    data = example_data()
    revised = copy.deepcopy(data["equations"][0])
    revised["revision"] = "next"
    data["equations"].append(revised)
    source = write_contract(tmp_path, data)
    graph = build_graph(paths=[source], root=tmp_path)
    nodes = [node for node in graph["nodes"] if node["type"] == "equation"
             and node["ref"]["id"] == revised["id"]]
    assert len(nodes) == 2 and nodes[0]["id"] != nodes[1]["id"]
    assert {node["ref"]["revision"] for node in nodes} == {data["equations"][0]["revision"], "next"}


def test_documentation_keeps_revision_links_math_and_binding_locations(tmp_path):
    data = example_data()
    second = copy.deepcopy(data["equations"][0])
    second["revision"] = "next"
    second["description"] = "An alternative, unassessed equation revision."
    data["equations"].append(second)
    source = write_contract(tmp_path, data)
    catalog = docs.Catalog(tmp_path / "generated")
    entry = catalog.add("fixture", tmp_path, source.name)
    records = docs.records_page(catalog, entry)
    claims = docs.assessments_page(entry)
    review = docs.assessment_page(entry, entry.contract.assessments[0])
    for equation in entry.contract.equations:
        anchor = entry.anchor("equation", equation.id, equation.revision)
        assert f".. _{anchor}:" in records
        assert "   " + equation.latex in records
        assert "Revision: " + docs.text(equation.revision) in records
        assert docs.text(equation.scope) in records
        for symbol in equation.symbols.values():
            assert docs.inline_math(symbol.latex) in records
            assert docs.text(symbol.description) in records
            assert docs.text(symbol.unit) in records
    assert ".. math::\n" in records
    equation = entry.contract.equations[0]
    assert entry.link("equation", equation.id, equation.revision,
                      label=f"{equation.id} ({equation.revision})") in claims
    assert entry.link("equation", equation.id, equation.revision) in review
    assert entry.anchor("equation", second["id"], second["revision"]) not in review
    for binding in entry.contract.bindings:
        assert f".. _{entry.anchor('binding', binding.id)}:" in records
        assert entry.link("equation", binding.equation.id, binding.equation.revision) in records
        assert entry.link("subject", binding.subject) in records
        assert docs.text(binding.source) in records and docs.text(binding.symbol) in records
        assert entry.link("binding", binding.id) in review


def test_document_generation_does_not_renew_stale_review_pins(tmp_path):
    data = example_data()
    original = data["assessments"][0]["equation_pins"][0]["sha256"]
    data["equations"][0]["assumptions"].append("A newly recorded restriction.")
    source = write_contract(tmp_path, data)
    before = source.read_bytes()
    catalog = docs.Catalog(tmp_path / "generated")
    entry = catalog.add("fixture", tmp_path, source.name)
    review = docs.assessment_page(entry, entry.contract.assessments[0])
    assert original in review
    assert equation_digest(entry.contract.equations[0]) != original
    assert "this document build does not recheck their hashes" in review
    assert source.read_bytes() == before


@pytest.mark.skipif(shutil.which("pdflatex") is None, reason="Optional TeX compiler is unavailable")
def test_fragment_compiles_in_a_provider_owned_document(tmp_path):
    data = example_data()
    data["equations"][0]["description"] = r"Symbols with 50% & {braces}, rate_1 and \prose."
    (tmp_path / "equations.tex").write_text(render_equations(ContractV03.model_validate(data)), encoding="utf-8")
    (tmp_path / "model.tex").write_text(
        "\\documentclass{article}\n\\usepackage{amsmath}\n\\begin{document}\n"
        "\\input{equations.tex}\n\\end{document}\n", encoding="utf-8",
    )
    result = subprocess.run(["pdflatex", "-no-shell-escape", "-interaction=nonstopmode", "-halt-on-error",
                             "model.tex"], cwd=tmp_path, capture_output=True, text=True, timeout=30)
    assert result.returncode == 0, result.stdout
    assert (tmp_path / "model.pdf").is_file()
